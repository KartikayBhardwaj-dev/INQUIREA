    async def plan(
        self,
        question: str,
    ) -> QueryPlan:
        """
        Generate a structured retrieval plan from a user's natural language
        inbox question.

        This method also performs validation and normalization to ensure
        downstream retrieval always receives a usable QueryPlan.
        """

        chain = (
            self.prompt.partial(
                format_instructions=self.parser.get_format_instructions(),
            )
            | llm
            | self.parser
        )

        try:
            plan: QueryPlan = await chain.ainvoke(
                {
                    "question": question,
                }
            )

        except Exception:
            # Safe fallback if the LLM or parser fails.
            return QueryPlan(
                intent="semantic_search",
                semantic_query=question,
                category=None,
                priority=None,
                sender=None,
                requires_reply=None,
                retrieve_limit=5,
                sort_by="relevance",
                date_from=None,
                date_to=None,
                reasoning="Fallback retrieval plan generated after planner failure.",
            )

        # --------------------------------------------------
        # Validation / Normalization
        # --------------------------------------------------

        # Use the original question if no semantic query was produced.
        if not plan.semantic_query:
            plan.semantic_query = question

        # Normalize priority.
        if plan.priority:
            plan.priority = plan.priority.lower().strip()

            allowed = {
                "low",
                "medium",
                "high",
                "urgent",
            }

            if plan.priority not in allowed:
                plan.priority = None

        # Normalize category.
        if plan.category:
            plan.category = plan.category.lower().strip()

        # Normalize sender.
        if plan.sender:
            plan.sender = plan.sender.strip()

        # Clamp retrieve_limit.
        plan.retrieve_limit = max(
            1,
            min(
                plan.retrieve_limit,
                50,
            ),
        )

        # Validate sorting.
        if plan.sort_by not in {
            "relevance",
            "date",
            "priority",
        }:
            plan.sort_by = "relevance"

        # Summaries should retrieve more emails.
        if (
            plan.intent == "summarize"
            and plan.retrieve_limit < 20
        ):
            plan.retrieve_limit = 20

        # Deadline searches should default to date sorting.
        if (
            plan.intent == "deadline_search"
            and plan.sort_by != "date"
        ):
            plan.sort_by = "date"

        return plan

