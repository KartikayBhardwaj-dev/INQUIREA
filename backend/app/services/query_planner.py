class QueryPlan(BaseModel):
    """
    Structured retrieval plan generated by the LLM.

    This object is consumed by ChatRetriever to perform
    semantic retrieval and metadata filtering.
    """

    intent: Literal[
        "semantic_search",
        "summarize",
        "sender_lookup",
        "deadline_search",
        "metadata_search",
    ] = Field(
        description="Overall intent of the user's request."
    )

    semantic_query: str | None = Field(
        default=None,
        description=(
            "Optimized semantic search query. "
            "Rewrite vague user questions into better search phrases."
        ),
    )

    category: str | None = Field(
        default=None,
        description="Email category filter.",
    )

    priority: Literal[
        "low",
        "medium",
        "high",
        "urgent",
    ] | None = Field(
        default=None,
        description="Priority filter.",
    )

    sender: str | None = Field(
        default=None,
        description="Specific sender if requested.",
    )

    requires_reply: bool | None = Field(
        default=None,
        description=(
            "Whether only emails requiring a reply "
            "should be returned."
        ),
    )

    retrieve_limit: int = Field(
        default=5,
        ge=1,
        le=50,
        description="Maximum number of emails to retrieve.",
    )

    sort_by: Literal[
        "relevance",
        "date",
        "priority",
    ] = Field(
        default="relevance",
        description="Sorting strategy.",
    )

    date_from: str | None = Field(
        default=None,
        description="Inclusive ISO date lower bound.",
    )

    date_to: str | None = Field(
        default=None,
        description="Inclusive ISO date upper bound.",
    )

    reasoning: str = Field(
        description="Short explanation of the chosen retrieval plan.",
    )


